#!/usr/bin/env python3
"""Generate one localAI domain-baseline machine per accepted domain.

localAIStack contributes eight hand-written machines, and only one domain
(health-personal) has any domain-specific ones: personal_health_baseline and
medication_adherence, written by hand for the HealthKit/CareKit integration.
Every other domain in `RealityEngine_Machines domains/domain-manifest.json` has
no localAI-side machine at all, so coverage followed whoever built an
integration rather than the domain list (RealityEngine_Machines#219).

This generates the missing ones. For each accepted domain it writes
`data/machines/generated/<domain>_baseline.json`, a `localai/<domain>_baseline`
machine with the same shape as personal_health_baseline:

  input   4 cells  localAIStack writes a worst-state-wins roll-up one-hot
                   [thriving, balanced, watch, attention] (sensor
                   localai_<domain>_rollup, declared inactive, active on its
                   first value)
  output  4 cells  the machine asserts the matching state; an all-zero input
                   fires <domain>-none and retracts the output to all zero

Regions are 8 cells per domain from the free tail of the band reserved for
localAIStack (`localaistack-integration`, [7440:7952]), starting above the
health slots [7600:7632]. `config/domain-machine-slots.json` fixes each domain's
slot the first time it is generated and never reassigns it: a new domain is
appended, so no existing region moves (moving a region is a contract change).

health-personal is not generated; its two hand-written machines cover it, and
HANDWRITTEN names them so the coverage check can tell "covered by hand" from
"forgotten".

Usage:
    scripts/generate_domain_machines.py            # write (assigns slots to new domains)
    scripts/generate_domain_machines.py --check    # regenerate in memory; exit 1 on disagreement
    MACHINES_DIR=/path/to/RealityEngine_Machines scripts/generate_domain_machines.py

`--check` never writes. A stale file is reported with the command that fixes it
and is a failure only because the regenerated bytes differ from what is checked
in; the checked-in files are never hand-edited.
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = REPO / "data" / "machines" / "generated"
SLOTS_PATH = REPO / "config" / "domain-machine-slots.json"
INDEX_PATH = REPO / "config" / "domain-machines.index.json"

# The band the corpus registry reserves for this repo, and where the generated
# machines start inside it: the first cell above the health slots [7600:7632].
BAND = (7440, 7952)
SLOT_BASE = 7632
CELLS_PER_SLOT = 8  # 4 in + 4 out
SLOT_CAPACITY = (BAND[1] - SLOT_BASE) // CELLS_PER_SLOT

# Domains whose localAI machines are written by hand. Covered, not generated.
HANDWRITTEN: dict[str, list[str]] = {
    "health-personal": ["personal_health_baseline.json", "medication_adherence.json"],
}

STATES = ("thriving", "balanced", "watch", "attention")
CREATED = "2026-10-24T00:00:00Z"  # fixed: the output must be reproducible
TTL_MS = 86_400_000


HEALTH_BANDS_PATH = REPO / "data" / "health" / "health_bands.json"


def health_slot_window() -> tuple[int, int]:
    """The cells the dynamic HealthKit band slots occupy, from their own table."""
    table = json.loads(HEALTH_BANDS_PATH.read_text(encoding="utf-8"))["slotTable"]
    return table["offset"], table["offset"] + table["capacity"]


def rel(path: pathlib.Path) -> str:
    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def snake(domain: str) -> str:
    return domain.replace("-", "_")


def label(domain: str) -> str:
    return domain.replace("-", " ")


def manifest_path() -> pathlib.Path:
    root = os.environ.get("MACHINES_DIR")
    candidates = [pathlib.Path(root)] if root else []
    candidates.append(REPO.parent / "RealityEngine_Machines")
    for candidate in candidates:
        path = candidate / "domains" / "domain-manifest.json"
        if path.is_file():
            return path
    sys.exit(
        "[fail] domains/domain-manifest.json not found under a sibling "
        "RealityEngine_Machines checkout — set MACHINES_DIR"
    )


def manifest_domains() -> list[str]:
    manifest = json.loads(manifest_path().read_text(encoding="utf-8"))
    # `domains` is keyed by domain id.
    return sorted(
        d for d, entry in manifest["domains"].items() if entry.get("status") == "accepted"
    )


def load_slots() -> dict[str, int]:
    if not SLOTS_PATH.is_file():
        return {}
    return dict(json.loads(SLOTS_PATH.read_text(encoding="utf-8"))["slots"])


def slots_text(slots: dict[str, int]) -> str:
    doc = {
        "schemaVersion": "1.0.0",
        "purpose": (
            "Slot of each domain's generated localAI machine inside the band reserved for "
            "localAIStack. A slot is assigned the first time a domain is generated and never "
            "reassigned: slot n holds input [SLOT_BASE+8n : +4] and output [+4 : +8]. Generated "
            "by scripts/generate_domain_machines.py; do not renumber."
        ),
        "slotBase": SLOT_BASE,
        "cellsPerSlot": CELLS_PER_SLOT,
        "slots": dict(sorted(slots.items(), key=lambda kv: kv[1])),
    }
    return json.dumps(doc, indent=2) + "\n"


def regions(slot: int) -> tuple[dict, dict]:
    base = SLOT_BASE + CELLS_PER_SLOT * slot
    return {"offset": base, "length": 4}, {"offset": base + 4, "length": 4}


def span(region: dict) -> str:
    return f"[{region['offset']}:{region['offset'] + region['length']}]"


def one_hot(index: int) -> list[float]:
    return [1.0 if i == index else 0.0 for i in range(4)]


def build_machine(domain: str, slot: int) -> dict:
    s, lab = snake(domain), label(domain)
    inp, out = regions(slot)
    sensor = f"localai_{s}_rollup"
    descriptions = {
        "thriving": f"Every graded measure in the {lab} domain is in its nominal range.",
        "balanced": f"Exactly one graded measure in the {lab} domain is slightly outside its nominal range, none well outside.",
        "watch": f"Two or more graded measures in the {lab} domain are slightly outside their nominal ranges, none well outside.",
        "attention": f"At least one graded measure in the {lab} domain is well outside its nominal range.",
        "none": (
            f"Nothing in the {lab} domain is graded. The roll-up is all zero, so the output is "
            "retracted to all zero: no state, rather than the last state held by a region nothing rewrites."
        ),
    }
    hints = {
        "thriving": f"Every {lab} measure in scope is in its nominal range.",
        "balanced": f"One {lab} measure in scope is slightly outside its nominal range. A gentle nudge is enough.",
        "watch": f"Several {lab} measures in scope are slightly outside their nominal ranges. Suggest an easier day and attention to the basics.",
        "attention": f"At least one {lab} measure in scope is well outside its nominal range. Recommend a check-in.",
        "none": f"No current {lab} data is in scope.",
    }

    sequences, input_sequences, rules = [], [], []
    for index, state in enumerate(STATES + ("none",)):
        sid = f"{s}-{state}"
        vector = one_hot(index) if state != "none" else [0.0, 0.0, 0.0, 0.0]
        if state == "none":
            elements = [{"value": 0.0, "threshold": 0.5} for _ in range(4)]
            check_desc = "every element LOW (<0.5, gte with value 0): the all-zero roll-up"
            seq_name = "None: roll-up all LOW"
            out_text = "[0,0,0,0] — none"
        else:
            elements = [
                {"value": 1.0, "threshold": 0.5}
                if i == index
                else {"value": 0.5, "threshold": 0.5, "comparatorType": "threshold"}
                for i in range(4)
            ]
            check_desc = (
                f"element[{index}]: roll-up {state} HIGH (>=0.5); other elements: wildcard "
                "(the input is one-hot)"
            )
            seq_name = f"{state.capitalize()}: roll-up[{index}] HIGH"
            out_text = f"{json.dumps([int(v) for v in vector], separators=(',', ':'))} — {state}"
        sequences.append(
            {
                "id": sid,
                "name": seq_name,
                "metadata": {"description": descriptions[state], "output": out_text},
                "events": [
                    {
                        "id": f"{sid}-check",
                        "isInitial": True,
                        "nextEventIds": [],
                        "elements": elements,
                        "outputEvents": [
                            {
                                "id": f"{sid}-out",
                                "vector": vector,
                                "metadata": {
                                    "description": f"{descriptions[state]} — {state}",
                                    "state": state,
                                    "ragStatusCode": "GREEN",
                                    "promptHint": hints[state],
                                },
                            }
                        ],
                        "metadata": {"name": f"{state.upper()}_CHECK", "description": check_desc},
                    }
                ],
            }
        )
        input_sequences.append(
            {
                "name": f"Roll-up {state}" if state != "none" else "Nothing graded — no state",
                "pattern": (
                    f"roll-up one-hot [{index}] → {state}"
                    if state != "none"
                    else f"roll-up all zero → {sid} retracts the output"
                ),
                "description": (
                    f"localAIStack wrote roll-up state {state}. Should assert {state} "
                    f"{json.dumps([int(v) for v in vector], separators=(',', ':'))}."
                    if state != "none"
                    else f"Nothing in the {lab} domain is graded. The roll-up is all zero; {sid} "
                    "fires and writes [0,0,0,0], so no state is asserted rather than the last one held."
                ),
                "events": [vector],
                "metadata": {
                    "expectedOutput": json.dumps([int(v) for v in vector], separators=(",", ":")),
                    "activeSequence": sid,
                },
            }
        )
        rules.append(
            {
                "sequenceId": sid,
                "outputMatches": vector,
                "ragStatusCode": "GREEN",
                "processStatus": "info",
                "description": descriptions[state],
            }
        )

    process_id = "LOCALAI" + s.replace("_", "").upper() + "BASELINE"
    return {
        "version": "1.0.0",
        "machine": {
            "name": f"localai/{s}_baseline",
            "description": (
                f"{lab.capitalize()} domain state classifier, generated from "
                "domains/domain-manifest.json by scripts/generate_domain_machines.py — do not edit by hand. "
                f"Reads the worst-state-wins roll-up that localAIStack writes at {span(inp)} as a one-hot "
                f"[thriving, balanced, watch, attention] and asserts the matching state at {span(out)}. "
                "All sequences are isInitial under PASSTHROUGH; the input is one-hot, so at most one "
                f"fires per step, and an all-zero input (nothing graded) fires {s}-none, which retracts "
                "the output to all zero."
            ),
            "metadata": {
                "category": domain,
                "author": "localAIStack domain-machine generator",
                "created": CREATED,
                "pattern": "domain-state-classifier",
                "eventSpace": f"4D roll-up one-hot at {span(inp)}: [thriving, balanced, watch, attention], written by localAIStack (sensor {sensor})",
                "outputSpace": f"4D classification at {span(out)}: [thriving, balanced, watch, attention]",
                "tags": ["localai", "domain-baseline", "classifier", domain],
                "sensorSources": {
                    sensor: {
                        "region": span(inp),
                        "description": (
                            f"Worst-state-wins roll-up over the graded {lab} measures, one-hot; "
                            "all zero when nothing is graded. Declared inactive, active on its first value."
                        ),
                        "ttlMs": TTL_MS,
                    }
                },
                "stateLogic": {
                    "thriving": descriptions["thriving"],
                    "balanced": descriptions["balanced"],
                    "watch": descriptions["watch"],
                    "attention": descriptions["attention"],
                    "none": f"Nothing graded — the roll-up is all zero; {s}-none retracts the output to all zero",
                    "mutualExclusivity": "The roll-up is one-hot, so no two sequences fire in the same step",
                },
                "localAIPromptHints": {st: hints[st] for st in STATES},
                "sequenceCount": 5,
                "machineClass": "signal-monitor",
                "governance": {
                    "schemaVersion": "1.0.0",
                    "ownerTeam": "localaistack",
                    "runbook": f"https://runbooks.example.org/localai/{domain}-baseline",
                    "escalationPolicy": "slack:#localaistack",
                    "contact": {
                        "primary": "localaistack-primary@example.org",
                        "secondary": "localaistack-secondary@example.org",
                    },
                    "sla": {"ok": None, "info": None, "warning": None, "error": None},
                    "notes": "localAIStack integration machine, registered into the RE at runtime by the reality bridge rather than loaded from the corpus.",
                },
                "triggerConfig": {
                    "processId": process_id,
                    "processName": f"LocalAI {lab.title()} Baseline",
                    "rules": rules,
                },
            },
            "arbiterRule": "PASSTHROUGH",
            "matchAlgorithm": "gte",
            "perceptualMapping": {"input": inp, "output": out, "bitsPerElement": 8},
            "sequences": sequences,
            "inputSequences": input_sequences,
        },
    }


def machine_text(domain: str, slot: int) -> str:
    return json.dumps(build_machine(domain, slot), indent=2, ensure_ascii=False) + "\n"


def index_text(slots: dict[str, int], domains: list[str]) -> str:
    machines = []
    for domain in domains:
        if domain in HANDWRITTEN:
            continue
        inp, out = regions(slots[domain])
        s = snake(domain)
        machines.append(
            {
                "domain": domain,
                "name": f"localai/{s}_baseline",
                "file": f"data/machines/generated/{s}_baseline.json",
                "slot": slots[domain],
                "input": inp,
                "output": out,
                "sensorId": f"localai_{s}_rollup",
            }
        )
    doc = {
        "schemaVersion": "1.0.0",
        "purpose": (
            "Inventory of the localAI domain-baseline machines generated per accepted domain, and "
            "of the domains covered by hand-written ones. Generated by "
            "scripts/generate_domain_machines.py; the sensor declarations and the RC3 machine "
            "inventory read this file."
        ),
        "band": {"offset": BAND[0], "length": BAND[1] - BAND[0]},
        "slotBase": SLOT_BASE,
        "slotCapacity": SLOT_CAPACITY,
        "generated": machines,
        "handWritten": {d: HANDWRITTEN[d] for d in domains if d in HANDWRITTEN},
    }
    return json.dumps(doc, indent=2) + "\n"


def expected_outputs(domains: list[str], slots: dict[str, int]) -> dict[pathlib.Path, str]:
    files: dict[pathlib.Path, str] = {}
    for domain in domains:
        if domain in HANDWRITTEN:
            continue
        files[OUT_DIR / f"{snake(domain)}_baseline.json"] = machine_text(domain, slots[domain])
    files[SLOTS_PATH] = slots_text(slots)
    files[INDEX_PATH] = index_text(slots, domains)
    return files


def plan_slots(domains: list[str], slots: dict[str, int]) -> dict[str, int]:
    """Existing slots are kept; each new domain takes the lowest free slot, in id order."""
    planned = dict(slots)
    taken = set(planned.values())
    for domain in domains:
        if domain in HANDWRITTEN or domain in planned:
            continue
        slot = next(n for n in range(SLOT_CAPACITY + 1) if n not in taken)
        if slot >= SLOT_CAPACITY:
            sys.exit(
                f"[fail] no free slot for domain '{domain}': the band's free tail "
                f"[{SLOT_BASE}:{BAND[1]}] holds {SLOT_CAPACITY} domain machines. Widening the "
                "band is a contract change (RealityEngine_Machines domains/domain-registry.json)."
            )
        planned[domain] = slot
        taken.add(slot)
    return planned


def check(domains: list[str], slots: dict[str, int]) -> list[str]:
    problems: list[str] = []
    missing = [d for d in domains if d not in HANDWRITTEN and d not in slots]
    for d in missing:
        problems.append(f"domain '{d}' has no slot — run scripts/generate_domain_machines.py")
    for d, slot in slots.items():
        if d not in domains:
            problems.append(
                f"slot table names '{d}' which is not an accepted domain in the manifest — "
                "remove it deliberately (and its machine); a slot is never reused silently"
            )
        if d in HANDWRITTEN:
            problems.append(f"'{d}' is hand-written but also has a slot")
        if not 0 <= slot < SLOT_CAPACITY:
            problems.append(f"slot {slot} for '{d}' is outside 0..{SLOT_CAPACITY - 1}")
    if len(set(slots.values())) != len(slots):
        problems.append("two domains share a slot")
    health_lo, health_hi = health_slot_window()
    if health_hi > SLOT_BASE and health_lo < SLOT_BASE + CELLS_PER_SLOT * SLOT_CAPACITY:
        problems.append(
            f"generated slots [{SLOT_BASE}:{BAND[1]}] overlap the health slot table [{health_lo}:{health_hi}] "
            "(data/health/health_bands.json)"
        )
    for d, names in HANDWRITTEN.items():
        if d not in domains:
            problems.append(f"HANDWRITTEN names '{d}' which is not an accepted domain")
        for name in names:
            if not (REPO / "data" / "machines" / name).is_file():
                problems.append(f"hand-written machine for '{d}' is missing: data/machines/{name}")
    if problems:
        return problems

    expected = expected_outputs(domains, slots)
    for path, text in expected.items():
        if not path.is_file():
            problems.append(f"{rel(path)} is missing")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{rel(path)} differs from a regeneration")
    if OUT_DIR.is_dir():
        for path in sorted(OUT_DIR.glob("*.json")):
            if path not in expected:
                problems.append(f"{rel(path)} is not generated for any accepted domain")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory; exit 1 on disagreement, never write",
    )
    args = parser.parse_args()

    domains = manifest_domains()
    slots = load_slots()

    if args.check:
        problems = check(domains, slots)
        for problem in problems:
            print(f"[fail] {problem}", file=sys.stderr)
        if problems:
            print("[fail] regenerate with: scripts/generate_domain_machines.py", file=sys.stderr)
            return 1
        generated = [d for d in domains if d not in HANDWRITTEN]
        print(
            f"generate-domain-machines: {len(generated)} generated + {len(HANDWRITTEN)} hand-written "
            f"domain(s) cover all {len(domains)} accepted domains; files match a regeneration"
        )
        return 0

    slots = plan_slots(domains, slots)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    changed = 0
    for path, text in expected_outputs(domains, slots).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed += 1
            print(f"wrote {rel(path)}")
    wanted = {OUT_DIR / f"{snake(d)}_baseline.json" for d in domains if d not in HANDWRITTEN}
    for path in sorted(OUT_DIR.glob("*.json")):
        if path not in wanted:
            print(
                f"[warn] {rel(path)} is not generated for any accepted domain — remove it deliberately"
            )
    print(f"generate-domain-machines: {changed} file(s) written, {len(domains)} domain(s) covered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
